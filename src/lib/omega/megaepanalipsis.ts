/**
 * X105 — ΜΕΓΑΛΥΤΕΡΗ-ΕΠΑΝΑΛΗΨΙΣ ("maximal repeat"), the MR-order codec.
 *
 * THE IMPORTED RESULT, RESTATED WITH ITS HYPOTHESES.
 * Maruyama et al., "Practical Grammar Compression Based on Maximal Repeats",
 * Axioms 2020, 9(4), 63; arXiv:1811.04596v2.  They analyse the grammar
 * generation of RePair and prove:
 *
 *   Theorem 1 (their numbering, from [17]).  If there is just one most frequent
 *   maximal repeat in the current text, RePair replaces all occurrences of it
 *   step by step.
 *
 *   Remark 1.  If there are several distinct pairs with the same maximum
 *   frequency, the size of the grammar generated by RePair depends on the
 *   replacement order of them.
 *
 *   Theorem 4 (their Theorem 2 of [17]).  The sizes of grammars generated by
 *   RePair are the same if they are generated in the same MR-order.
 *
 *   Theorem 6 (their numbering).  The grammar can be larger in MR-RePair than in
 *   RePair if their MR-orders are different.
 *
 * Their experimental result is the reason this file exists: MR-RePair, which
 * substitutes the most frequent maximal repeats at once instead of substituting
 * the most frequent pairs consecutively, produced 4 492 rules against RePair's
 * 41 661 on rand77.txt (10.8 %) and 21 787 against 49 933 on einstein.de.txt
 * (43.6 %).  They also state the effect was limited on the Large Corpus texts,
 * which are not highly repetitive.
 *
 * HYPOTHESES.  Their object is a straight-line grammar over an alphabet with no
 * tokenizer and no per-symbol cost model: the objective is grammar size in
 * symbols, the counts are occurrence counts, and every rule costs one symbol.
 * ΧΕΙΡΩΝ's object is a token sequence under a fixed tokenizer: the objective is
 * the token count of the emitted wire, a rule costs a glyph plus its value, and
 * the candidate score is the token bound `c*(t-1)-t-1`, not the count.  So the
 * theorem's CONCLUSION transfers only at the level of the ORDER, and the
 * direction of the effect must be measured, not assumed.
 *
 * WHAT THE ORDER IS IN ΧΕΙΡΩΝ, MEASURED.
 * ΧΕΙΡΩΝ's macro loop ranks candidates by the exact token bound, then takes a
 * window `cands.slice(offset, offset + EPOCH_APPLY*5)` and applies at most
 * `EPOCH_APPLY = 12` of them.  After each epoch `offset += EPOCH_APPLY*5`.  So
 * the MR-order ΧΕΙΡΩΝ realises is
 *
 *     rank 0..11, then rank 60..71, then rank 120..131, ...
 *
 * Ranks 12..59, 72..119, ... are never applied in that run unless a later
 * re-enumeration happens to re-rank them into a fresh window.  The order is
 * therefore NOT monotone in the bound, and by Theorem 4's shape the final size
 * is a function of the MR-order alone, so the size ΧΕΙΡΩΝ reaches is the size
 * belonging to THAT order, not to the best available order.
 *
 * THE MECHANISM.  Make the order monotone in the bound and skip only candidates
 * that are demonstrably dead, instead of skipping a fixed positional block:
 *
 *   - the window is always the head of the current ranking, after the dead set;
 *   - a candidate joins the dead set only when it is observed not to apply
 *     (its phrase is absent from the body and from every literal rule, or
 *     `addRule` refuses it), never merely because it was ranked below the cut;
 *   - `offset` therefore advances by the number of dead candidates encountered,
 *     which is what the positional `offset += EPOCH_APPLY*5` was approximating.
 *
 * This is not a tie-break.  ΤΑΞΙΝΟΜΗΣΙΣ (X104) decides which of several
 * equally-ranked candidates survives a cut; this changes which ranks are
 * considered at all, and it changes the order in which maximal repeats are
 * completed.  The two compose: ΜΕΓΑΛΥΤΕΡΗ-ΕΠΑΝΑΛΗΨΙΣ decides the window
 * contents, ΤΑΞΙΝΟΜΗΣΙΣ decides the order inside a tie.
 *
 * DISABLE.  `OMEGA_NO_MEGAEPANALIPSIS=1` restores the positional window
 * exactly, so the A/B control is the shipped behaviour and not a variant.
 */
/** How many candidates a window may hold.  Mirrors `EPOCH_APPLY*5` in chiron.ts. */
export const MEGAEPANALIPSIS_WINDOW = 60;

/**
 * Read the enable flag once per call, never at module load.  (X104: a
 * load-time const in this repository read the environment before the probe set
 * it, and the flag silently never took effect anywhere in the repo.)
 */
export function megaepanalipsisDisabled(): boolean {
  return process.env?.OMEGA_NO_MEGAEPANALIPSIS === '1';
}

/** The candidate shape ΧΕΙΡΩΝ ranks, restated so this module owns no tokenizer. */
export interface MegaepanalipsisCand {
  /** The phrase the rule would be built from. */
  p: string;
  /** Exact token bound `c*(t-1)-t-1`, the quantity the ranking is monotone in. */
  bound: number;
  /** Occurrence count. */
  c: number;
  /** Token length of `p`. */
  t: number;
}

/**
 * The MR-order window.
 *
 * @param ranked  the full candidate list, already sorted by descending bound
 * @param offset  the number of leading candidates already consumed
 * @param dead    phrases observed not to apply; mutated by the caller as it goes
 * @param limit   window width
 * @returns the window, in rank order
 */
export function megaepanalipsisWindow<T extends MegaepanalipsisCand>(
  ranked: readonly T[],
  offset: number,
  dead: ReadonlySet<string>,
  limit: number = MEGAEPANALIPSIS_WINDOW,
): T[] {
  const out: T[] = [];
  for (let i = Math.max(0, offset); i < ranked.length && out.length < limit; i++) {
    if (!dead.has(ranked[i]!.p)) out.push(ranked[i]!);
  }
  return out;
}

/**
 * How far the offset should advance after one epoch.
 *
 * The shipped rule advances by `EPOCH_APPLY*5` regardless of what happened.
 * This advances past exactly the leading candidates that are dead, so a live
 * candidate ranked below the cut is considered on the next epoch instead of
 * being skipped forever.  Returns 0 when nothing at the head is dead, which is
 * the common case and means "re-rank from the top", i.e. a monotone MR-order.
 */
export function megaepanalipsisAdvance(
  ranked: readonly MegaepanalipsisCand[],
  offset: number,
  dead: ReadonlySet<string>,
): number {
  let i = Math.max(0, offset);
  while (i < ranked.length && dead.has(ranked[i]!.p)) i++;
  return i;
}

/**
 * Registry wrapper, so the arm appears in the census and can be priced on its
 * own.  ΧΕΙΡΩΝ itself carries the macro loop; this arm only selects its order,
 * so encoding is ΧΕΙΡΩΝ's and decoding is `chironDecode`.
 */
export function megaepanalipsisEncode(text: string, enc: any, opts?: any): any {
  // Lazy import so a probe that only wants the policy does not pay for chiron.
  const chiron = require('./chiron');
  return chiron.chironEncode(text, enc, { ...(opts ?? {}), mrOrder: true });
}

export function megaepanalipsisDecode(wire: string): string {
  const chiron = require('./chiron');
  return chiron.chironDecode(wire);
}
