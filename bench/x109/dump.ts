import * as fs from 'node:fs';
import { tagstackEncode } from '../../src/lib/omega/tagstack';
import { countTokens, tokenStrings } from '../../src/lib/omega/bpe';
import { CHIRON_START } from '../../src/lib/omega/chiron';
process.env.OMEGA_DET='1'; process.env.OMEGA_NO_MEMO='1'; process.env.OMEGA_ENGRAM='0'; process.env.OMEGA_OURA_MEMO='0'; process.env.OMEGA_NO_OROTHESIA='1';
const enc:any='o200k_base';
const p=process.argv[2]!;
const r:any=tagstackEncode(fs.readFileSync(p,'utf8'),enc);
const msg:string=r.message;
const w=msg.indexOf(CHIRON_START); const tEnd=msg.indexOf('\u00b6',w);
console.log('=== RAW ('+countTokens(fs.readFileSync(p,'utf8'),enc)+' tok) ===');
console.log(JSON.stringify(fs.readFileSync(p,'utf8').slice(0,700)));
console.log('\n=== CONTRACT ('+countTokens(msg.slice(0,w),enc)+' tok) ===');
console.log(msg.slice(0,w));
console.log('\n=== TAPE ('+countTokens(msg.slice(w+1,tEnd),enc)+' tok) ===');
console.log(JSON.stringify(msg.slice(w+1,tEnd)));
console.log('\n=== BODY ('+countTokens(msg.slice(tEnd+1),enc)+' tok) ===');
console.log(JSON.stringify(msg.slice(tEnd+1).slice(0,900)));
console.log('\n=== BODY TOKENS ===');
console.log(JSON.stringify(tokenStrings(msg.slice(tEnd+1),enc).slice(0,120)));
