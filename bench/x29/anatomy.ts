import fs from 'node:fs';
import { syntomosEncode } from '@/lib/omega/syntomos';
import { chironParseTape } from '@/lib/omega/chiron';
import { scriptOfChar } from '@/lib/omega/syntomia';
import { countTokens } from '@/lib/omega/bpe';
const enc = 'o200k_base' as any;
const T = (s: string) => countTokens(s, enc);
const f = process.env.F!;
const t = fs.readFileSync(f, 'utf8');
const r: any = syntomosEncode(t, enc);
const si = r.wire.indexOf('¶'); const tape = r.wire.slice(1, si), body = r.wire.slice(si+1);
const sc: any = scriptOfChar(tape[0]);
const parsed: any[] = chironParseTape(tape, sc) || [];
const gs = new Set(parsed.map(p=>p.glyph));
const runs: number[] = []; let cur=0, gl=0;
for (const ch of body) { if (gs.has(ch)) { cur++; gl++; } else { if(cur) runs.push(cur); cur=0; } }
if (cur) runs.push(cur);
const d: Record<number,number> = {}; for (const L of runs) d[Math.min(L,6)] = (d[Math.min(L,6)]||0)+1;
const lit = [...body].filter((c:string)=>!gs.has(c)).join('');
const gTok = T(body) - T(lit);
console.log(f.split('/').pop(), '| raw', r.inTokens, '| msg', r.messageTokens, '| rules', parsed.length);
console.log('  tape', T(tape), '| body', T(body), '| contract', T(r.contract));
console.log('  glyph chars', gl, '| runs', runs.length, '| gTok', gTok, '| cost/glyph', (gl?(gTok/gl).toFixed(3):'-'));
console.log('  run-length hist (1..6+):', JSON.stringify(d));
console.log('  isolated', d[1]||0, '-> floor cost', d[1]||0, 'tokens; non-isolated glyphs', gl-(d[1]||0));
console.log('  LITERAL body chars', lit.length, '-> tokens', T(lit));
console.log('  literal chars/token', (lit.length/T(lit)).toFixed(3));
console.log('  === BODY head (600 chars) ===');
console.log(JSON.stringify(body.slice(0,600)));
