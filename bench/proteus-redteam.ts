await ok('missing body boundary is inert',async()=>assert.equal(await proteusDecode('⬥!abc'),'⬥!abc'));
await ok('empty expansion tape is inert',async()=>assert.equal(await proteusDecode('⬥!乙x'),'⬥!乙x'));
await ok('ordinal expansion is exact',async()=>assert.equal(await proteusDecode(`⬥!xyz乙${THEMIS_IMPLICIT_GLYPHS[0]}`),'xyz'));
await ok('ordinary METIS fallback delegates',async()=>assert.equal(await proteusDecode(base.wire),input));
await ok('same-chat access model explicit',()=>assert.ok(proteusDecoderPrompt().includes('No system prompt')));
await ok('prompt specifies adaptive delimiter protocol',()=>assert.ok(proteusDecoderPrompt().includes('next single character is delimiter d')));
await ok('exact Pareto tournament',()=>assert.ok(r.outTokens<=base.outTokens));
console.log(`\n${n}/19 PROTEUS adversarial passes`);
