import fs from 'node:fs';
const CLOCK = '((?:T\\d{6})|(?:\\d{2}:\\d{2}:\\d{2}))';
const OFFSET = '[+-]\\d{2}:\\d{2}|Z';
const t = fs.readFileSync('bench/z20/samples/git-log-iso.txt', 'utf8');
const clocks = t.match(new RegExp(CLOCK, 'g')) || [];
const withAny = t.match(new RegExp(`${CLOCK}(?:${OFFSET})`, 'g')) || [];
console.log('clocks', clocks.length, 'withAny', withAny.length);
console.log('sample clocks', clocks.slice(0, 3));
console.log('sample withAny', withAny.slice(0, 3));
const tally = new Map<string, number>();
for (const m of t.matchAll(new RegExp(`${CLOCK}(${OFFSET})`, 'g'))) tally.set(m[1], (tally.get(m[1]) ?? 0) + 1);
console.log('tally', [...tally.entries()]);
const suffix = '+00:00';
const esc = suffix.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
console.log('esc', JSON.stringify(esc));
const re = new RegExp(`${CLOCK}${esc}`, 'g');
console.log('apply regex', re.source);
const stripped = t.replace(re, '$1');
console.log('stripped changed?', stripped !== t, 'removed', (t.length - stripped.length));
const renderRe = new RegExp(`${CLOCK}(?!\\s*(?:${OFFSET}))`, 'g');
console.log('render regex', renderRe.source);
console.log('render(stripped)===t ?', stripped.replace(renderRe, `$1${suffix}`) === t);
