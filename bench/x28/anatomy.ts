import fs from 'node:fs';
import { metathesisEncode } from '@/lib/omega/metathesis';
import { countTokens } from '@/lib/omega/bpe';
const enc = 'o200k_base' as any;
const T = (s: string) => countTokens(s, enc);
const f = process.env.F || 'bench/holdout-work/kb-article.txt';
const t = fs.readFileSync(f, 'utf8');
const r: any = metathesisEncode(t, enc);
console.log('FILE', f, 'in', r.inTokens, 'msg', r.messageTokens, 'rules', r.rules);
console.log('parent', r.parent, 'order', r.order, 'shapes', JSON.stringify(r.shapes));
console.log('--- RAW WIRE (first 700 chars) ---');
console.log(JSON.stringify(r.wire.slice(0, 700)));
const SEP = '¶', START = '§';
const w = r.wire;
const si = w.indexOf(SEP);
const tape = w.slice(1, si), body = w.slice(si + 1);
console.log('--- token split ---');
console.log('wire total   ', T(w));
console.log('  tape       ', T(tape), '(', tape.length, 'chars )');
console.log('  body       ', T(body), '(', body.length, 'chars )');
console.log('  delims     ', T(START) * 1 + T(SEP) * 1, '(START+SEP)');
console.log('contract     ', T(r.contract || ''));
// count glyph chars in tape vs phrase chars
const glyphRe = /[Ѐ-ӿ]/g;
const glyphs = tape.match(glyphRe) || [];
console.log('  glyph chars in tape', glyphs.length, '-> tokens', T(glyphs.join('')), 'isolated');
console.log('--- TAPE first 400 chars ---');
console.log(JSON.stringify(tape.slice(0, 400)));
console.log('--- BODY first 300 chars ---');
console.log(JSON.stringify(body.slice(0, 300)));
